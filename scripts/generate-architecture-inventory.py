"""Generate a static architecture inventory without importing application modules.

Run from any directory: python scripts/generate-architecture-inventory.py
The inventory records evidence, not runtime reachability or feature support.
"""
import ast
from collections import Counter, defaultdict
from pathlib import Path
import re
import tokenize


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "architecture-inventory.md"


def main():
    modules = []
    errors = []
    topics = defaultdict(list)
    duplicates = []
    actions = []
    crossings = []
    for path in sorted((ROOT / "src").rglob("*.py")):
        if any(part in {"__pycache__", ".pytest_cache", "dist", "build", "config", "logs"} for part in path.parts):
            continue
        relative = path.relative_to(ROOT).as_posix()
        with tokenize.open(path) as stream:
            source = stream.read()
        try:
            tree = ast.parse(source)
        except SyntaxError as exc:
            errors.append((relative, exc.lineno, exc.msg))
            # Keep visible definitions even in syntactically invalid modules.
            definitions = [(i, line.strip()) for i, line in enumerate(source.splitlines(), 1)
                           if re.match(r"\s*(?:async )?(?:def|class) ", line)]
            modules.append((relative, definitions))
            continue
        definitions = []
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                definitions.append((node.lineno, node.name))
            elif isinstance(node, ast.ClassDef):
                methods = [child for child in node.body if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef))]
                definitions.append((node.lineno, "class " + node.name))
                definitions.extend((method.lineno, node.name + "." + method.name) for method in methods)
                counts = Counter(method.name for method in methods)
                for name, count in counts.items():
                    if count > 1:
                        duplicates.append((relative, node.lineno, node.name + "." + name, count))
            if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == "actions" for target in node.targets) and isinstance(node.value, ast.Dict):
                for key in node.value.keys:
                    if isinstance(key, ast.Constant):
                        actions.append((relative, key.lineno, str(key.value)))
        modules.append((relative, definitions))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            func = ast.unparse(node.func)
            if func in {"pub.sendMessage", "pub.subscribe", "pub.unsubscribe"}:
                position = 0 if func == "pub.sendMessage" else 1
                topic = ast.unparse(node.args[position]) if len(node.args) > position else "<keyword/dynamic>"
                keys = ", ".join(kw.arg or "**kwargs" for kw in node.keywords)
                topics[topic].append((relative, node.lineno, func, keys))
            if (".api." in func or "._ensure_client" in func or "community_api." in func
                    or (relative.startswith("src/sessions/") and func.startswith(("wx.", "output.", "webbrowser.")))
                    or (relative == "src/config_utils.py" and "commonMessageDialogs" in func)):
                crossings.append((relative, node.lineno, func))
    lines = ["# Static architecture inventory", "",
             "Generated by `scripts/generate-architecture-inventory.py`. Does not import or run TWBlue.", "",
             "Complements the [roadmap](architecture-roadmap.md). A definition or event does not prove reachability or working behavior. Dynamic calls require manual review.", "",
             f"Modules examined: {len(modules)}. Syntax errors: {len(errors)}. Includes tests/utilities; excludes caches, configuration data and builds.", "",
             "## Syntax errors", ""]

    def ref(path, number, label):
        return f"[{label}](../{path}#L{number})"

    for path, number, message in errors:
        lines.append(f"- {ref(path, number, path)}: line {number}, `{message}`.")
    lines += ["", "## Methods redefined within the same class", ""]
    for path, number, name, count in duplicates:
        lines.append(f"- {ref(path, number, name)}: {count} definitions; Python keeps the last one.")
    lines += ["", "## Declared keyboard actions", ""]
    for path, number, name in actions:
        lines.append(f"- {ref(path, number, name)} — `{path}`.")
    lines += ["", "## Events: producers and consumers", "",
              "Topics are shown as Python expressions. Arguments are keyword names, without values or credentials.", ""]
    for topic, entries in sorted(topics.items()):
        lines += [f"### `{topic}`", ""]
        for path, number, function, keys in entries:
            lines.append(f"- {ref(path, number, path + ':' + str(number))}: `{function}`; keywords: `{keys or 'none'}`.")
        lines.append("")
    lines += ["## Dependency review points", "",
              "Heuristic: direct API calls; wx, speech or browser calls in sessions; dialogs in configuration. This is not a complete dependency checker.", ""]
    for path, number, function in crossings:
        lines.append(f"- {ref(path, number, path + ':' + str(number))}: `{function}`.")
    lines += ["", "## Definitions by module", "",
              "Module functions, classes and direct methods. Closures are not listed. Invalid modules use text extraction.", ""]
    for path, definitions in modules:
        lines += [f"### `{path}`", ""]
        if not definitions:
            lines.append("No direct definitions (may contain initialization or data).")
        for number, name in definitions:
            lines.append(f"- {ref(path, number, name)}")
        lines.append("")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(modules)} modules, {len(errors)} syntax errors, {len(duplicates)} duplicate methods")


if __name__ == "__main__":
    main()
